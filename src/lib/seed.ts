export function sampleComps(key: keyof typeof examples, date = today()): Comparable[] {
  const prices =
    key === 'fleece' ? [42, 48, 54, 65] : key === 'lamp' ? [28, 32, 38, 45] : [15, 18, 22, 26];
  return prices.map((price, i) => ({
    id: `demo-${key}-${i}`,
    key: itemKey(examples[key]),
    title: examples[key].title,
    platform: ['eBay', 'Poshmark', 'eBay', 'Etsy'][i],
    price,
    kind: i === 3 ? 'asking' : 'sold',
    date,
    source: 'demo',
    url: '',
    condition: 'Good',
  }));
}
